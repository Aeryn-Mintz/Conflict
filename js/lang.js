window.applyLang = function(lang) {
    if (!window.conflictTranslations[lang]) lang = 'en';
    localStorage.setItem('conflictLang', lang); 
    const t = window.conflictTranslations[lang];

    const setTxt = (id, txt) => { const el = document.getElementById(id); if (el && txt) el.innerText = txt; };
    const setSelTxt = (sel, txt) => { const el = document.querySelector(sel); if (el && txt) el.innerText = txt; };
    const setPlh = (id, txt) => { const el = document.getElementById(id); if (el && txt) el.placeholder = txt; };

    // 1. Launcher & Networks
    setTxt('launcher-subtitle', t.launcherSubtitle);
    setTxt('saved-networks-title', t.savedNetworksTitle);
    setTxt('host-game-btn', t.hostGame);
    setTxt('join-game-btn', t.joinGame);
    setTxt('btn-open-active-room', t.openRoomBtn);
    setTxt('btn-disconnect-bg-lan', t.disconnectBtn);
    setTxt('create-net-heading', t.createNetHeading);
    setTxt('create-net-desc', t.createNetDesc);
    setPlh('new-net-name-input', t.newNetNamePlh);
    setTxt('btn-confirm-create-net', t.confirmCreateNet);
    setTxt('btn-back-host', t.backBtn);
    setTxt('join-net-heading', t.joinNetHeading);
    setTxt('opt1-code-label', t.opt1CodeLabel);
    setPlh('join-net-name-input', t.joinNetNamePlh);
    setPlh('invite-input', t.inviteInputPlh);
    setTxt('btn-connect-join', t.saveAndJoinBtn);
    setTxt('opt2-radar-label', t.opt2RadarLabel);
    setTxt('radar-spinner', t.radarScanning);
    setTxt('scan-rooms-btn', t.scanRooms);
    setTxt('btn-back-join', t.backBtn);
    setTxt('update-msg', t.updateCheck);

    if (typeof window.renderSavedNetworks === 'function') window.renderSavedNetworks();

    // 2. Sidebar & Navigation Tabs
    setSelTxt('#network-switcher-box h4', t.activeNetworkTitle);
    const sidebarHeaders = document.querySelectorAll('.sidebar .sidebar-section > h4');
    if (sidebarHeaders.length > 0) {
        sidebarHeaders.forEach(h => {
            if (h.parentElement.id !== 'network-switcher-box') {
                h.innerText = t.myProfileTitle;
            }
        });
    }
    setSelTxt('.sidebar .panel-header-row h4', t.soundboardTitle);
    setSelTxt('.status-pill-online', t.onlineStatusPill);

    setSelTxt('.tab-btn[data-tab="main"]', t.tabMain);
    setSelTxt('.tab-btn[data-tab="rpg"]', t.tabRpg);
    setTxt('tab-vault-btn', t.charVault);
    setTxt('tab-dm-btn', t.tabDm);
    setTxt('char-vault-title', t.charVault);

    setTxt('settings-btn', t.settings);
    setTxt('connected-users-btn', t.connectedUsers);
    setTxt('leave-room-btn', t.leaveRoom);
    setTxt('add-sound-btn', t.addSoundBtn);

    // 3. Live Stage & Call Buttons
    setSelTxt('#video-grid .drag-handle h3', t.liveStageTitle);
    const joinBtn = document.getElementById('join-voice-btn');
    if (joinBtn && !joinBtn.disabled) {
        joinBtn.innerText = window.inVoiceCall ? t.leaveCall : t.joinCall;
    }
    setTxt('mute-mic-btn', window.isMuted ? t.unmute : t.mute);
    setTxt('toggle-cam-btn', window.localCamStream ? t.stopCam : t.camera);
    setTxt('share-screen-btn', window.localScreenStream ? t.stopShare : t.shareScreen);

    // 4. Media Player, Queue & Chat
    setSelTxt('#drag-media .drag-handle h3', t.mediaPlayerTitle);
    setPlh('yt-url-input', t.ytUrlPlh);
    setTxt('yt-play-btn', t.ytPlayBtn);
    setTxt('toggle-queue-btn', t.ytQueueBtn);
    const nowPlaying = document.getElementById('yt-now-playing-title');
    if (nowPlaying && (!window.ytQueue || window.ytQueue.length === 0)) {
        nowPlaying.innerText = t.ytNoTrack;
    }
    setSelTxt('#drag-yt-queue .drag-handle h3', t.playlistQueueTitle);
    setTxt('save-pl-btn', t.savePlBtn);
    setTxt('load-pl-btn', t.loadPlBtn);
    setTxt('restore-pl-btn', t.restorePlBtn);
    setSelTxt('.yt-queue-header span:first-child', t.upNextHeader);

    setSelTxt('#drag-chat .drag-handle h3', t.roomChatTitle);
    setPlh('chat-input', t.chatPlaceholder);
    setTxt('chat-send-btn', t.chatSendBtn);

    // 5. VTT, Character Vault & DM Screen
    setTxt('expand-vtt-toolbar-btn', t.showToolbarBtn);
    setTxt('toggle-tokens-btn', t.assetsBtn);
    setTxt('dm-force-system', t.broadcastBtn);
    setTxt('scenes-manager-btn', t.scenesBtn);
    setSelTxt('#floating-token-panel .drag-handle h3', t.tokenVaultTitle);
    setTxt('claim-dm-btn', window.isDM ? t.releaseDm : t.claimDm);
    setTxt('sheet-save-status', t.autoSavedBadge);
    setTxt('view-party-btn', window.viewingParty ? t.myCharacter : t.partySheets);
    setTxt('new-char-btn', t.newCharacter);
    setSelTxt('#sheets-view .panel > h4', t.heroPortraitTitle);
    setTxt('spawn-char-token-btn', t.spawnTokenBtn);
    setTxt('map-upload-btn', t.mapUpload);
    setTxt('restore-map-btn', t.restoreMap);
    setTxt('add-token-btn', t.addToken);

    setSelTxt('#dm-view h3.rpg-heading', t.dmSanctumTitle);
    const dmSubHeaders = document.querySelectorAll('#dm-view h4');
    if (dmSubHeaders[0]) dmSubHeaders[0].innerText = t.livePartySheetsTitle;
    if (dmSubHeaders[1]) dmSubHeaders[1].innerText = t.bestiaryTitle;
    setTxt('add-npc-btn', t.addNpcBtn);

    // 6. Settings, Screen Picker & Cropper Modals
    const cfgTitle = document.querySelector('#config-view .drag-handle h3');
    if (cfgTitle) {
        const logoImg = cfgTitle.querySelector('img');
        cfgTitle.innerHTML = '';
        if (logoImg) cfgTitle.appendChild(logoImg);
        cfgTitle.appendChild(document.createTextNode(' ' + t.settingsModalTitle));
    }
    const startupInput = document.getElementById('startup-toggle');
    if (startupInput && startupInput.parentElement) {
        startupInput.parentElement.innerHTML = '';
        startupInput.parentElement.appendChild(startupInput);
        startupInput.parentElement.appendChild(document.createTextNode(' ' + t.startupLabel));
    }
    setPlh('username-input', t.displayNamePlh);
    setTxt('change-avatar-btn', t.uploadAvatarBtn);
    setTxt('reset-theme-btn', t.resetThemeBtn);
    setTxt('refresh-devices-btn', t.refreshDevicesBtn);
    setTxt('save-theme-btn', t.saveSettingsBtn);
    setTxt('lang-label', t.langLabel);

    const cfgHeadings = document.querySelectorAll('#config-view .panel-content h3');
    if (cfgHeadings[0]) cfgHeadings[0].innerText = t.themeColorsTitle;
    if (cfgHeadings[1]) cfgHeadings[1].innerText = t.hardwareSettingsTitle;

    const cfgLabels = document.querySelectorAll('#config-view .config-label');
    if (cfgLabels[0]) cfgLabels[0].innerText = t.displayNameLabel;
    if (cfgLabels[1]) cfgLabels[1].innerText = t.micLabel;
    if (cfgLabels[2]) cfgLabels[2].innerText = t.outDeviceLabel;
    if (cfgLabels[3]) cfgLabels[3].innerText = t.webcamLabel;
    if (cfgLabels[4]) cfgLabels[4].innerText = t.noiseGateLabel;

    setSelTxt('#screen-picker-modal h3', t.screenPickerTitle);
    setTxt('cancel-screen-picker', t.cancelBtn);
    setSelTxt('#crop-modal h3', t.cropModalTitle);
    setTxt('cancel-crop-btn', t.cancelBtn);
    setTxt('save-crop-btn', t.applyCropBtn);

    // Sync dropdown & flags
    const selectEl = document.getElementById('language-select');
    if (selectEl) selectEl.value = lang;

    document.querySelectorAll('.lang-flag').forEach(el => {
        el.style.borderColor = 'transparent';
        el.style.transform = 'scale(1)';
        el.style.boxShadow = 'none';
    });
    const activeFlag = document.getElementById(lang === 'en' ? 'flag-en' : 'flag-pt-br');
    if (activeFlag) {
        activeFlag.style.borderColor = 'var(--accent-main)';
        activeFlag.style.transform = 'scale(1.1)';
        activeFlag.style.boxShadow = '0 0 10px var(--accent-main)';
    }

    if (typeof window.renderConnectedUsers === 'function') window.renderConnectedUsers();
};

document.addEventListener('DOMContentLoaded', () => {
    let savedLang = localStorage.getItem('conflictLang');
    if (!savedLang) savedLang = navigator.language.toLowerCase().includes('pt') ? 'pt-br' : 'en';
    window.applyLang(savedLang);
    
    document.getElementById('language-select')?.addEventListener('change', (e) => window.applyLang(e.target.value));
    document.getElementById('flag-en')?.addEventListener('click', () => window.applyLang('en'));
    document.getElementById('flag-pt-br')?.addEventListener('click', () => window.applyLang('pt-br'));
});